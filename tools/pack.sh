#!/bin/bash
# Build both foundation plugins, the pipeline adapters, the SDK package and the templates package, and
# lay out the foundation's install folders under artifacts/ — what a release ships.
#
# Usage: tools/pack.sh [IL2CPP interop dir]
#
# Four parts compile against assemblies that have no NuGet package. Each one is read from a folder
# you point at (only read; never copy it into the repository). A part without its folder is LEFT OUT
# with a warning that says what that costs, so a fresh clone builds everything else:
#   URP17_REF_DIR       the URP 17 adapter (Unity 6 URP): a Unity 6 URP game's <Game>_Data/Managed, or
#                       a Unity 6 URP project's Library/ScriptAssemblies. Default: the testbed's
#                       unity/AstraTestbed/Library/ScriptAssemblies, once it has been opened or built.
#   URP14_REF_DIR       the URP 14 adapter (Unity 2022-2023 URP): a Unity 2022.3 URP game's
#                       <Game>_Data/Managed.
#   HDRP_REF_DIR        the HDRP adapter: an HDRP game's <Game>_Data/Managed, or an HDRP project's
#                       Library/ScriptAssemblies. Default: unity/AstraTestbedHdrp's, if there is one.
#   IL2CPP_INTEROP_DIR  the IL2CPP plugin (or this script's first argument): a BepInEx/interop folder
#                       BepInEx 6 generated for an IL2CPP game. Default: the testbed's IL2CPP build's,
#                       once BepInEx 6 has started it.
# ASTRA_PACK_REQUIRE="urp17 urp14 hdrp il2cpp" (any of them, or "all") turns a missing part into an
# error before anything is built; il2cpp builds that plugin as a release (it refuses an interop that
# stripped something the foundation uses). Only "all" packs the SDK and the template package as a
# RELEASE (package version = the foundation's); any other run packs <version>-dev, and a run with no
# IL2CPP plugin packs the SDK as <version>-mono-dev — never the id and version of a published package.
# tools/make-runner-gi.sh is the run that makes a release's packages (CONTRIBUTING.md, "Releasing").
set -euo pipefail
cd "$(dirname "$0")/.."

# The older spellings still work: the MSBuild properties UrpRefDir and Il2CppInteropDir.
URP17=${URP17_REF_DIR:-${UrpRefDir:-}}
[ -n "$URP17" ] || URP17=unity/AstraTestbed/Library/ScriptAssemblies
URP14=${URP14_REF_DIR:-}
HDRP=${HDRP_REF_DIR:-}
[ -n "$HDRP" ] || HDRP=unity/AstraTestbedHdrp/Library/ScriptAssemblies
INTEROP=${1:-${IL2CPP_INTEROP_DIR:-${Il2CppInteropDir:-}}}
[ -n "$INTEROP" ] || INTEROP=unity/AstraTestbed/Build/il2cpp/BepInEx/interop
REQUIRE=" ${ASTRA_PACK_REQUIRE:-} "
[ "$REQUIRE" = " all " ] && REQUIRE=" urp17 urp14 hdrp il2cpp "

# has <dir> <file>…: does the folder hold every one of the files?
has() { local d=$1; shift; [ -n "$d" ] || return 1; for f; do [ -f "$d/$f" ] || return 1; done; }

# Which parts can be built — decided (and a required one refused) before anything is built.
declare -A ok=() left=()
check() { # check <part> <how to provide it> <what is lost without it> <dir> <files…>
  local part=$1 how=$2 cost=$3 dir=$4; shift 4
  if has "$dir" "$@"; then ok[$part]=1; return; fi
  local where="'$dir' has no $1"
  [ -n "$dir" ] || where="none given"
  local msg="no $part references: $where. Set $how. Without it $cost."
  if [[ "$REQUIRE" == *" $part "* ]]; then echo "pack.sh: $msg" >&2; exit 1; fi
  left[$part]=$msg
}
check urp17 "URP17_REF_DIR to a Unity 6 URP game's <Game>_Data/Managed (or open or build the testbed once)" \
  "the foundation draws Unity 6 URP games after the camera instead of inside its render" \
  "$URP17" Unity.RenderPipelines.Universal.Runtime.dll Unity.RenderPipelines.Core.Runtime.dll
check urp14 "URP14_REF_DIR to a Unity 2022.3 URP game's <Game>_Data/Managed" \
  "the foundation draws URP 2022-2023 games over the finished frame" \
  "$URP14" UnityEngine.CoreModule.dll Unity.RenderPipelines.Universal.Runtime.dll Unity.RenderPipelines.Core.Runtime.dll
check hdrp "HDRP_REF_DIR to an HDRP game's <Game>_Data/Managed" \
  "the foundation draws HDRP games without a depth test (over the walls)" \
  "$HDRP" Unity.RenderPipelines.HighDefinition.Runtime.dll Unity.RenderPipelines.Core.Runtime.dll
check il2cpp "IL2CPP_INTEROP_DIR (or the first argument) to an IL2CPP game's BepInEx/interop, generated by BepInEx 6 on the game's first start" \
  "there is no IL2CPP foundation, and the SDK package carries no net6.0 (IL2CPP) API" \
  "$INTEROP" UnityEngine.CoreModule.dll

dotnet build src/Astra.BepInEx5 -c Release -v q
if [ -n "${ok[urp17]:-}" ]; then
  dotnet build src/Astra.Urp17 -c Release -v q -p:UrpRefDir="$URP17"
fi
if [ -n "${ok[urp14]:-}" ]; then
  dotnet build src/Astra.Urp14 -c Release -v q -p:UrpRefDir="$URP14"
fi
if [ -n "${ok[hdrp]:-}" ]; then
  dotnet build src/Astra.Hdrp -c Release -v q -p:HdrpRefDir="$HDRP"
fi
IL2CPP_RELEASE=false
[[ "$REQUIRE" == *" il2cpp "* ]] && IL2CPP_RELEASE=true
if [ -n "${ok[il2cpp]:-}" ]; then
  dotnet build src/Astra.BepInEx6.IL2CPP -c Release -v q -p:Il2CppInteropDir="$INTEROP" -p:AstraRelease=$IL2CPP_RELEASE
fi
# The packages are a release only when every part was REQUIRED (and so built).
RELEASE=true
for part in urp17 urp14 hdrp il2cpp; do [[ "$REQUIRE" == *" $part "* ]] || RELEASE=false; done
SDK_FLAGS=(-p:AstraRelease=$RELEASE -p:AstraSdkIl2Cpp=$([ -n "${ok[il2cpp]:-}" ] && echo true || echo false))
dotnet pack src/Astra.Unity.Sdk -c Release -v q "${SDK_FLAGS[@]}"
dotnet pack templates/Astra.Unity.Templates.csproj -c Release -v q -p:AstraRelease=$RELEASE
SDK_VERSION=$(dotnet msbuild src/Astra.Unity.Sdk -getProperty:PackageVersion "${SDK_FLAGS[@]}")
TEMPLATES_VERSION=$(dotnet msbuild templates/Astra.Unity.Templates.csproj -getProperty:PackageVersion -p:AstraRelease=$RELEASE)

# The foundation as it is installed in a game: BepInEx/plugins/Astra/…
for flavour in mono il2cpp; do
  out=artifacts/foundation-$flavour/BepInEx/plugins/Astra
  rm -rf artifacts/foundation-$flavour
  if [ $flavour = mono ]; then
    src=src/Astra.BepInEx5/bin/Release/netstandard2.0
    mkdir -p "$out"
    if [ -n "${ok[urp17]:-}" ]; then cp src/Astra.Urp17/bin/Release/netstandard2.1/Astra.Urp17.dll "$out/"; fi
    if [ -n "${ok[urp14]:-}" ]; then cp src/Astra.Urp14/bin/Release/netstandard2.1/Astra.Urp14.dll "$out/"; fi
    if [ -n "${ok[hdrp]:-}" ]; then cp src/Astra.Hdrp/bin/Release/netstandard2.1/Astra.Hdrp.dll "$out/"; fi
  else
    [ -n "${ok[il2cpp]:-}" ] || continue
    src=src/Astra.BepInEx6.IL2CPP/bin/Release/net6.0
    mkdir -p "$out"
  fi
  cp $src/Astra.Unity.dll $src/Astra.Bridge.Core.dll $src/astra-item.json "$out/"
done
ls -R artifacts | head -40

# Said LAST, where it is read: what this build left out, and how to get it.
echo "wrote artifacts/nuget/Astra.Unity.Sdk.$SDK_VERSION.nupkg and Astra.Unity.Templates.$TEMPLATES_VERSION.nupkg$([ $RELEASE = true ] && echo ': a RELEASE' || echo ': prerelease packages, not a release')"
missing=""
for part in urp17 urp14 hdrp il2cpp; do
  if [ -n "${left[$part]:-}" ]; then missing="$missing $part"; fi
done
if [ -n "$missing" ]; then
  echo >&2
  echo "pack.sh: built WITHOUT$missing — fine for working on the foundation, not for a release:" >&2
  for part in $missing; do echo "  - ${left[$part]}" >&2; done
fi
exit 0
